"""
Project 2 - Logistics Operations BI
Stage 1A - Dataset Audit
Audit Findings Analysis

Purpose
-------
Analyze the structured outputs generated by dataset_audit.py.

This script:
    1. Finds the latest audit run.
    2. Reads the latest audit output files.
    3. Identifies important data-quality findings.
    4. Classifies findings by severity.
    5. Creates a findings report.
    6. Creates a functional execution log.

IMPORTANT
---------
- Raw data is NOT accessed or modified.
- Audit output files are READ ONLY.
- This script analyzes audit results only.
"""

from pathlib import Path
from datetime import datetime
import pandas as pd


# ============================================================
# 1. PROJECT PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

AUDIT_LOG_DIR = (
    PROJECT_ROOT
    / "logs"
    / "dataset_audit"
)


# ============================================================
# 2. FIND LATEST AUDIT RUN
# ============================================================

def find_latest_audit_timestamp():
    """
    Find the timestamp of the latest dataset audit run.
    """

    audit_logs = sorted(
        AUDIT_LOG_DIR.glob("audit_run_*.txt")
    )

    if not audit_logs:
        raise FileNotFoundError(
            "No dataset audit execution log found."
        )

    latest_log = audit_logs[-1]

    # Example:
    # audit_run_20260820_172802.txt
    timestamp = (
        latest_log.stem
        .replace("audit_run_", "")
    )

    return timestamp


# ============================================================
# 3. LOAD AUDIT OUTPUT
# ============================================================

def load_audit_file(prefix, timestamp):
    """
    Load the audit CSV corresponding to the
    latest audit timestamp.
    """

    file_path = (
        AUDIT_LOG_DIR
        / f"{prefix}_{timestamp}.csv"
    )

    if not file_path.exists():
        raise FileNotFoundError(
            f"Required audit file not found:\n"
            f"{file_path}"
        )

    return pd.read_csv(file_path)


# ============================================================
# 4. FINDING STORAGE
# ============================================================

findings = []


def add_finding(
    severity,
    category,
    table,
    issue,
    evidence,
    recommendation,
):
    """
    Add a structured audit finding.
    """

    findings.append({

        "severity": severity,

        "category": category,

        "table": table,

        "issue": issue,

        "evidence": evidence,

        "recommendation": recommendation,

    })


# ============================================================
# 5. ANALYZE TABLE INVENTORY
# ============================================================

def analyze_inventory(df):

    for _, row in df.iterrows():

        table = row["table"]

        rows = row["rows"]

        columns = row["columns"]

        classification = row[
            "classification"
        ]

        if rows == 0:

            add_finding(
                "CRITICAL",
                "Table Structure",
                table,
                "Empty table",
                "Table contains 0 rows.",
                "Validate whether the table is intentionally empty before modelling."
            )

        elif rows < 10:

            add_finding(
                "LOW",
                "Table Structure",
                table,
                "Very small table",
                f"Table contains only {rows} rows.",
                "Validate whether the small volume is expected."
            )


# ============================================================
# 6. ANALYZE COLUMN QUALITY
# ============================================================

def analyze_columns(df):

    for _, row in df.iterrows():

        table = row["table"]

        column = row["column"]

        null_count = int(
            row["null_count"]
        )

        null_pct = float(
            row["null_pct"]
        )

        unique_count = int(
            row["unique_count"]
        )

        # ----------------------------------------------------
        # Missing values
        # ----------------------------------------------------

        if null_count > 0:

            if null_pct >= 50:

                severity = "HIGH"

            elif null_pct >= 10:

                severity = "MEDIUM"

            else:

                severity = "LOW"

            add_finding(
                severity,
                "Missing Data",
                table,
                f"Missing values in {column}",
                f"{null_count:,} null values ({null_pct:.2f}%).",
                "Determine whether missingness is expected, operationally meaningful, or requires transformation."
            )

        # ----------------------------------------------------
        # Constant column
        # ----------------------------------------------------

        if unique_count <= 1:

            add_finding(
                "MEDIUM",
                "Column Quality",
                table,
                f"Low-cardinality column: {column}",
                f"Only {unique_count} unique non-null value(s).",
                "Validate whether the column provides analytical value."
            )


# ============================================================
# 7. ANALYZE DUPLICATES
# ============================================================

def analyze_duplicates(df):

    for _, row in df.iterrows():

        table = row["table"]

        duplicates = int(
            row["duplicate_rows"]
        )

        if duplicates > 0:

            add_finding(
                "HIGH",
                "Duplicate Records",
                table,
                "Duplicate rows detected",
                f"{duplicates:,} duplicate rows.",
                "Investigate whether duplicates represent genuine repeated events or data-quality issues before removing anything."
            )


# ============================================================
# 8. ANALYZE PRIMARY KEYS
# ============================================================

def analyze_primary_keys(df):

    for _, row in df.iterrows():

        table = row["table"]

        duplicate_keys = row[
            "duplicate_key_rows"
        ]

        null_keys = row[
            "null_key_rows"
        ]

        # ----------------------------------------------------
        # Duplicate primary keys
        # ----------------------------------------------------

        if isinstance(
            duplicate_keys,
            (int, float)
        ) and duplicate_keys > 0:

            add_finding(
                "CRITICAL",
                "Primary Key Integrity",
                table,
                "Duplicate primary-key values",
                f"{int(duplicate_keys):,} rows participate in duplicate primary-key combinations.",
                "Validate table grain and determine whether the assumed primary key is actually correct."
            )

        # ----------------------------------------------------
        # Null primary keys
        # ----------------------------------------------------

        if isinstance(
            null_keys,
            (int, float)
        ) and null_keys > 0:

            add_finding(
                "CRITICAL",
                "Primary Key Integrity",
                table,
                "Null primary-key values",
                f"{int(null_keys):,} rows contain null key values.",
                "Investigate the table grain and source-system completeness before modelling relationships."
            )


# ============================================================
# 9. ANALYZE DATE QUALITY
# ============================================================

def analyze_dates(df):

    for _, row in df.iterrows():

        table = row["table"]

        column = row["column"]

        invalid_dates = int(
            row["invalid_dates"]
        )

        if invalid_dates > 0:

            add_finding(
                "HIGH",
                "Date Quality",
                table,
                f"Invalid date values in {column}",
                f"{invalid_dates:,} date values could not be parsed.",
                "Validate source formatting and standardize the date field before Power BI modelling."
            )


# ============================================================
# 10. ANALYZE NUMERIC QUALITY
# ============================================================

def analyze_numeric(df):

    for _, row in df.iterrows():

        table = row["table"]

        column = row["column"]

        negative_count = int(
            row["negative_count"]
        )

        if negative_count > 0:

            add_finding(
                "MEDIUM",
                "Numeric Quality",
                table,
                f"Negative values in {column}",
                f"{negative_count:,} negative values detected.",
                "Validate whether negative values are business-valid or indicate data-quality issues."
            )


# ============================================================
# 11. ANALYZE FOREIGN KEYS
# ============================================================

def analyze_foreign_keys(df):

    for _, row in df.iterrows():

        child_table = row[
            "child_table"
        ]

        child_column = row[
            "child_column"
        ]

        parent_table = row[
            "parent_table"
        ]

        parent_column = row[
            "parent_column"
        ]

        orphan_values = row[
            "orphan_values"
        ]

        if isinstance(
            orphan_values,
            (int, float)
        ) and orphan_values > 0:

            add_finding(
                "CRITICAL",
                "Referential Integrity",
                child_table,
                f"Orphan foreign-key values in {child_column}",
                f"{int(orphan_values):,} values do not match {parent_table}.{parent_column}.",
                "Investigate relationship integrity before creating the Power BI model."
            )

        elif isinstance(
            orphan_values,
            str
        ):

            if (
                "MISSING"
                in orphan_values
            ):

                add_finding(
                    "HIGH",
                    "Referential Integrity",
                    child_table,
                    f"Unable to validate {child_column}",
                    orphan_values,
                    "Review the source schema and audit definitions."
                )


# ============================================================
# 12. REMOVE DUPLICATE FINDINGS
# ============================================================

def remove_duplicate_findings():

    global findings

    unique_findings = []

    seen = set()

    for finding in findings:

        key = (
            finding["severity"],
            finding["category"],
            finding["table"],
            finding["issue"],
        )

        if key not in seen:

            seen.add(key)

            unique_findings.append(
                finding
            )

    findings = unique_findings


# ============================================================
# 13. GENERATE FINDINGS SUMMARY
# ============================================================

def generate_summary():

    if not findings:

        return {
            "CRITICAL": 0,
            "HIGH": 0,
            "MEDIUM": 0,
            "LOW": 0,
        }

    summary = {

        "CRITICAL": 0,

        "HIGH": 0,

        "MEDIUM": 0,

        "LOW": 0,

    }

    for finding in findings:

        severity = finding[
            "severity"
        ]

        if severity in summary:

            summary[severity] += 1

    return summary


# ============================================================
# 14. SAVE FINDINGS
# ============================================================

def save_findings(
    findings_df,
    timestamp
):

    output_file = (
        AUDIT_LOG_DIR
        / f"audit_findings_{timestamp}.csv"
    )

    findings_df.to_csv(
        output_file,
        index=False
    )

    return output_file


# ============================================================
# 15. SAVE FINDINGS REPORT
# ============================================================

def save_report(
    findings_df,
    summary,
    timestamp
):

    report_file = (
        AUDIT_LOG_DIR
        / f"audit_findings_report_{timestamp}.txt"
    )

    with open(
        report_file,
        "w",
        encoding="utf-8"
    ) as report:

        report.write(
            "PROJECT 2 - DATASET AUDIT FINDINGS\n"
        )

        report.write(
            "=" * 60 + "\n\n"
        )

        report.write(
            f"Audit timestamp: {timestamp}\n\n"
        )

        report.write(
            "FINDINGS SUMMARY\n"
        )

        report.write(
            "-" * 40 + "\n"
        )

        for severity, count in summary.items():

            report.write(
                f"{severity}: {count}\n"
            )

        report.write(
            "\nDETAILED FINDINGS\n"
        )

        report.write(
            "=" * 60 + "\n\n"
        )

        for index, row in findings_df.iterrows():

            report.write(
                f"{index + 1}. "
                f"[{row['severity']}] "
                f"{row['category']}\n"
            )

            report.write(
                f"Table: "
                f"{row['table']}\n"
            )

            report.write(
                f"Issue: "
                f"{row['issue']}\n"
            )

            report.write(
                f"Evidence: "
                f"{row['evidence']}\n"
            )

            report.write(
                f"Recommendation: "
                f"{row['recommendation']}\n"
            )

            report.write(
                "\n"
            )

    return report_file


# ============================================================
# 16. CREATE FUNCTIONAL LOG ENTRY
# ============================================================

def save_execution_log(
    timestamp,
    summary,
    output_files,
    start_time,
):

    end_time = datetime.now()

    duration = (
        end_time - start_time
    )

    log_file = (
        AUDIT_LOG_DIR
        / f"findings_analysis_run_{timestamp}.txt"
    )

    with open(
        log_file,
        "w",
        encoding="utf-8"
    ) as log:

        log.write(
            "PROJECT 2 - DATASET AUDIT "
            "FINDINGS ANALYSIS RUN\n"
        )

        log.write(
            "=" * 60 + "\n"
        )

        log.write(
            f"Start time: {start_time}\n"
        )

        log.write(
            f"End time: {end_time}\n"
        )

        log.write(
            f"Duration: {duration}\n\n"
        )

        log.write(
            "PURPOSE\n"
        )

        log.write(
            "Analyze the structured outputs produced "
            "by dataset_audit.py.\n\n"
        )

        log.write(
            "FINDINGS SUMMARY\n"
        )

        for severity, count in summary.items():

            log.write(
                f"{severity}: {count}\n"
            )

        log.write(
            "\nOUTPUT FILES\n"
        )

        for output_file in output_files:

            log.write(
                f"- {output_file.name}\n"
            )

        log.write(
            "\nTRACEABILITY NOTE\n"
        )

        log.write(
            "This analysis reads audit outputs only. "
            "Raw dataset files were not modified.\n"
        )

    return log_file


